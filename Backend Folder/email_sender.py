"""
Sends the PDF benchmark report to a user's email via Resend's HTTP API
(https://resend.com). Chosen over raw SMTP because it's a simple JSON POST
over HTTPS -- no risk of an outbound SMTP port being blocked or rate-limited
on a free-tier host, and Resend's free plan covers 3,000 emails/month.

Configuration (set as environment variables in Render, not in code):
  RESEND_API_KEY   -- required. Your Resend API key.
  RESEND_FROM      -- optional. Defaults to "onboarding@resend.dev", which
                      only works for sending to the email address on your
                      own Resend account until you verify a sending domain.
                      Once you verify a domain in Resend, set this to
                      something like "reports@yourdomain.com" so you can
                      email any recipient.
"""
import base64
import os

import requests

RESEND_API_URL = "https://api.resend.com/emails"


class EmailSendError(Exception):
    """Raised when the report email could not be sent."""


def send_report_email(to_email: str, pdf_bytes: bytes, industry_label: str, state_name: str) -> None:
    api_key = os.environ.get("RESEND_API_KEY")
    if not api_key:
        raise EmailSendError(
            "Email delivery isn't configured yet. Set the RESEND_API_KEY "
            "environment variable in Render to enable this feature."
        )

    from_address = os.environ.get("RESEND_FROM", "onboarding@resend.dev")
    subject = f"Your Industry Financial Benchmark report: {industry_label} ({state_name})"
    filename = f"{industry_label.replace(' ', '_')}_{state_name.replace(' ', '_')}_benchmark_report.pdf"

    payload = {
        "from": from_address,
        "to": [to_email],
        "subject": subject,
        "html": (
            f"<p>Your Industry Financial Benchmarks report for "
            f"<b>{industry_label}</b> in <b>{state_name}</b> is attached as a PDF.</p>"
            f"<p style=\"color:#5b6b74; font-size:12px;\">Generated by "
            f"industry-benchmarks.onrender.com, built from U.S. Census Bureau data "
            f"with modeled financial detail.</p>"
        ),
        "attachments": [
            {
                "filename": filename,
                "content": base64.b64encode(pdf_bytes).decode("ascii"),
            }
        ],
    }

    try:
        resp = requests.post(
            RESEND_API_URL,
            json=payload,
            headers={"Authorization": f"Bearer {api_key}"},
            timeout=30,
        )
    except requests.RequestException as e:
        raise EmailSendError(f"Could not reach the email service: {e}") from e

    if resp.status_code >= 400:
        try:
            detail = resp.json().get("message", resp.text)
        except ValueError:
            detail = resp.text
        raise EmailSendError(f"Email service rejected the request ({resp.status_code}): {detail}")
